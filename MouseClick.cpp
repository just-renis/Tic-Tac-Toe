void MouseClick::click(Vector2f pos, char size, vector<vector<Chunk*>>& chunks)
{
	switch (size)
	{
		case '1':
		for (int i{ -1 }; i < 1; i++)
		{
			for (int j{ -1 }; j < 1; j++)
			{
				//fluid.push_back(Fluid{ Vector2f{pos.x + i, pos.y + j}, this->type});
			}
		}
		break;
		case '2':
		for (int i{ 0 }; i < 20; i++)
		{
			for (int j{ 0 }; j < 20; j++)
			{
				if (this->circle2[i * 20 + j])
				{
					int x = pos.x + i - 10.f;
					int y = pos.y + j - 10.f;
					if (x >= 0 && y >= 0)
					{
						for (int k = 0; k < chunks.size(); k++)
						{
							for (int l = 0; l < chunks[k].size(); l++)
							{
								if (chunks[k][l]->getPos().x <= x && chunks[k][l]->getPos().x + 20.f > x)
								{
									if (chunks[k][l]->getPos().y <= y && chunks[k][l]->getPos().y + 20.f > y)
									{
										chunks[k][l]->createFluid("water", Vector2i{ x % 20, y % 20 });
										goto exit; // Exit the loops.
									}
								}
							}
						}
					}
				}
				exit: {}
			}
		}
		break;
	}
}